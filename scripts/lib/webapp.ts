/**
 * Vite plugin: makes the web build an installable, offline-capable web app
 * ("Add to Home Screen" on iPhone/iPad, "Install app" on Android Chrome).
 *
 * Emits into every build, nothing committed:
 *   manifest.webmanifest, icon-192.png, icon-512.png, icon-maskable-512.png,
 *   apple-touch-icon.png (all from scripts/lib/icons.ts), and sw.js.
 *
 * The service worker precaches every built file. Page loads are network-first with a 4 s timeout
 * (so a new version shows up on the next launch, and offline still works); everything else is
 * cache-first (file names are content-hashed); old caches are deleted on activate.
 * The dev server serves the manifest and icons, but no service worker.
 */
import { createHash } from 'node:crypto';
import type { Plugin } from 'vite';
import { BG, maskableIcon, squareIcon } from './icons.ts';

const NAME = 'Sorty McSort Sort';
const SHORT = 'Sorty';

const icons = async (): Promise<Record<string, Buffer>> => ({
  'icon-192.png': await squareIcon(192),
  'icon-512.png': await squareIcon(512),
  'icon-maskable-512.png': await maskableIcon(512),
  'apple-touch-icon.png': await squareIcon(180),
});

const manifest = () =>
  JSON.stringify(
    {
      name: NAME,
      short_name: SHORT,
      description: 'A block-sliding puzzle: tap blocks to slide them out, in the right order.',
      id: './',
      start_url: './',
      scope: './',
      display: 'standalone',
      orientation: 'portrait',
      background_color: BG,
      theme_color: BG,
      icons: [
        { src: 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
        { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
        { src: 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
      ],
    },
    null,
    2,
  );

const serviceWorker = (version: string, files: string[]) => `// Generated by scripts/lib/webapp.ts
const CACHE = 'sms-${version}';
const PRECACHE = ${JSON.stringify(['./', ...files])};
const INDEX = new URL('./', self.registration.scope).href;

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('sms-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

const timeout = (ms) => new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), ms));

// Page loads: network first (new versions show up on the next launch), cached index when offline.
async function page(req) {
  const cache = await caches.open(CACHE);
  try {
    const res = await Promise.race([fetch(req), timeout(4000)]);
    if (res.ok) cache.put(INDEX, res.clone());
    return res;
  } catch {
    return (await cache.match(INDEX)) || Response.error();
  }
}

// Everything else: cache first (built file names are content-hashed).
async function asset(req) {
  const hit = await caches.match(req);
  if (hit) return hit;
  const res = await fetch(req);
  if (res.ok) {
    const copy = res.clone();
    caches.open(CACHE).then((c) => c.put(req, copy));
  }
  return res;
}

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(req.mode === 'navigate' ? page(req) : asset(req));
});
`;

export function webApp(): Plugin {
  return {
    name: 'sorty-webapp',
    enforce: 'post', // after Vite's html plugin, so index.html is in the bundle
    configureServer(server) {
      const files: Promise<Record<string, Buffer>> = icons().then((i) => ({ ...i, 'manifest.webmanifest': Buffer.from(manifest()) }));
      server.middlewares.use((req, res, next) => {
        const name = (req.url ?? '').split('?')[0].replace(/^.*\//, '');
        files.then((f) => {
          const body = f[name];
          if (!body) return next();
          res.setHeader('Content-Type', name.endsWith('.png') ? 'image/png' : 'application/manifest+json');
          res.end(body);
        }, next);
      });
    },
    async generateBundle(_opts, bundle) {
      const own: Record<string, string | Buffer> = { ...(await icons()), 'manifest.webmanifest': manifest() };
      for (const [fileName, source] of Object.entries(own)) this.emitFile({ type: 'asset', fileName, source });
      // Files emitted above aren't in `bundle`'s keys, so add them to the precache list explicitly.
      const built = Object.keys(bundle).filter((f) => !f.endsWith('.map'));
      const files = [...new Set([...built, ...Object.keys(own)])].sort();
      const version = createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 12);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker(version, files) });
    },
  };
}
